"""Git data publisher with recovery before branch mutation."""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha1
from typing import Protocol

from .execution_guard import checkpoint

BRANCH = "rulebranch/rules-update"

class GitDataApi(Protocol):
    def branch_head(self, repository: dict[str, object], branch: str) -> str: ...
    def tree(self, repository: dict[str, object], commit_sha: str) -> dict[str, str]: ...
    def read_blob(self, repository: dict[str, object], sha: str) -> str: ...
    def blob(self, repository: dict[str, object], content: str) -> str: ...
    def new_tree(self, repository: dict[str, object], base_tree: str, entries: list[dict[str, object]]) -> str: ...
    def commit(self, repository: dict[str, object], tree_sha: str, parent_sha: str, message: str) -> str: ...
    def ref(self, repository: dict[str, object], branch: str, sha: str, force: bool) -> None: ...
    def open_pull_request(self, repository: dict[str, object], title: str, body: str, head: str, base: str, draft: bool) -> dict[str, object]: ...
    def edit_pull_request(self, repository: dict[str, object], number: int, body: str) -> None: ...
    def close_pull_request(self, repository: dict[str, object], number: int) -> None: ...
    def find_open_pull_request(self, repository: dict[str, object], head: str, base: str) -> dict[str, object] | None: ...

@dataclass(frozen=True)
class PublishedDraft:
    number: int
    url: str
    commit_sha: str
    created: bool


def draft_body(rule_version_ids: list[str]) -> str:
    rows = "\n".join(f"- `{value}`" for value in rule_version_ids) or "- (manual recompilation)"
    return f"## Approved RuleVersions\n{rows}\n\nGenerated by RuleBranch\n\nAI-generated proposals require human approval"


class GitHubPublisher:
    """Models never receive this publisher or its installation credentials."""
    def __init__(self, api: GitDataApi, auth: object | None = None) -> None:
        self._api, self._auth = api, auth

    def recover_open(self, repository: dict[str, object]) -> dict[str, object] | None:
        """Read-only: call before preparing artifacts against any branch."""
        checkpoint()
        remote = self._api.find_open_pull_request(repository, BRANCH, str(repository["defaultBranch"]))
        if remote is None:
            return None
        return {"prNumber": int(remote["number"]), "prUrl": str(remote["url"]),
                "branch": BRANCH, "status": "draft_open", "isDraft": True}

    def publication_snapshot(self, repository: dict[str, object], existing: dict[str, object] | None = None) -> tuple[str, dict[str, str]]:
        checkpoint()
        branch = BRANCH if existing is not None else str(repository["defaultBranch"])
        head = self._api.branch_head(repository, branch)
        return head, self._api.tree(repository, head)

    def read_blob(self, repository: dict[str, object], sha: str) -> str:
        return self._api.read_blob(repository, sha)

    def publication_tree(self, repository: dict[str, object], existing: dict[str, object] | None = None) -> dict[str, str]:
        return self.publication_snapshot(repository, existing)[1]

    def default_tree(self, repository: dict[str, object]) -> dict[str, str]:
        return self.publication_tree(repository)

    def publish(self, repository: dict[str, object], artifacts: list[dict[str, object]], rule_version_ids: list[str], existing: dict[str, object] | None = None, obsolete_paths: list[str] | None = None, expected_head: str | None = None) -> PublishedDraft:
        checkpoint()
        # A caller that prepared bytes from the default branch must not silently
        # recover a PR here: its manual content was not part of those inputs.
        if existing is None and self.recover_open(repository) is not None:
            raise ValueError("Unrecorded open PR found; retry compilation from its head before publication")
        if self._auth is not None:
            getattr(self._auth, "repository_token")(repository)
        branch = BRANCH if existing is not None else str(repository["defaultBranch"])
        base = self._api.branch_head(repository, branch)
        if expected_head is not None and base != expected_head:
            raise ValueError("Publication branch changed while instructions were prepared; retry compilation")
        entries: list[dict[str, object]] = []
        for artifact in artifacts:
            content = artifact.get("publicationContent", artifact.get("content"))
            if not isinstance(content, str):
                raise ValueError(f"Missing publication content for {artifact.get('path')}")
            raw = content.encode("utf-8")
            actual = sha1(b"blob " + str(len(raw)).encode("ascii") + b"\0" + raw).hexdigest()
            expected = artifact.get("gitBlobSha")
            if expected is not None and str(expected) != actual:
                raise ValueError(f"Publication content hash mismatch for {artifact.get('path')}")
            checkpoint()
            entries.append({"path": str(artifact["path"]), "mode": "100644", "type": "blob", "sha": self._api.blob(repository, content)})
        artifact_paths = {str(artifact["path"]) for artifact in artifacts}
        entries.extend({"path": path, "mode": "100644", "type": "blob", "sha": None} for path in sorted(set(obsolete_paths or []) - artifact_paths))
        checkpoint()
        tree = self._api.new_tree(repository, base, entries)
        checkpoint()
        commit = self._api.commit(repository, tree, base, "RuleBranch generated rules")
        # Catch movement while creating Git objects, not just before it.
        checkpoint()
        if self._api.branch_head(repository, branch) != base:
            raise ValueError("Publication branch changed before ref update; retry compilation")
        if existing is None and self.recover_open(repository) is not None:
            raise ValueError("Open PR appeared before ref update; retry compilation from its head")
        checkpoint()
        self._api.ref(repository, BRANCH, commit, force=existing is None)
        body = draft_body(rule_version_ids)
        checkpoint()
        if existing is not None:
            self._api.edit_pull_request(repository, int(existing["prNumber"]), body)
            return PublishedDraft(int(existing["prNumber"]), str(existing["prUrl"]), commit, False)
        # An uncertain create response is recovered on the next compile attempt,
        # before reading/preparing the managed instruction files.
        created = self._api.open_pull_request(repository, "RuleBranch rules update", body, BRANCH, str(repository["defaultBranch"]), True)
        return PublishedDraft(int(created["number"]), str(created["url"]), commit, True)
