"""Deterministic, storage-free RuleBranch Markdown compiler (IMPL-013)."""
from __future__ import annotations

from dataclasses import asdict, dataclass, field, is_dataclass
from hashlib import sha1, sha256
from typing import Any, Mapping, Sequence
from .managed_instructions import managed_block
from .relation_scope import uncovered_relation_fields


HEADER = "Generated by RuleBranch. Do not edit manually. AI-generated proposals require human approval."
AUTO_HEADER = "Generated by RuleBranch. Do not edit manually. Includes rules approved by delegated policy. GitHub merges require human review."
COMPILER_VERSION = "impl-013-v6"
MAX_ARTIFACT_CONTENT_BYTES = 200 * 1024


def _approval_header(versions: Sequence[Mapping[str, Any]]) -> str:
    return AUTO_HEADER if any(_mapping(version.get("approvalReview")).get("state") == "auto_approved" for version in versions) else HEADER


@dataclass(frozen=True)
class CompiledArtifact:
    """An unsaved compiled artifact.  Persistence belongs to IMPL-014."""

    target: str
    path: str
    contentHash: str
    content: str | None
    contentOmitted: bool
    gitBlobSha: str
    ruleId: str | None
    compilerVersion: str = COMPILER_VERSION
    # Firestore intentionally omits large artifact bodies, but the publisher
    # must still receive the exact bytes used to calculate gitBlobSha.  Keep
    # that transient publication payload separate from ``content`` so callers
    # cannot accidentally turn a storage limit into an empty Git blob.
    publicationContent: str = field(default="", repr=False)


def git_blob_sha(content: str) -> str:
    """Return Git's SHA-1 object id without invoking the git executable."""
    raw = content.encode("utf-8")
    return sha1(b"blob " + str(len(raw)).encode("ascii") + b"\0" + raw).hexdigest()


def compile(input: Mapping[str, Any] | Any) -> list[CompiledArtifact]:  # noqa: A001
    """Compile a resolved snapshot into deterministic Markdown artifacts.

    ``input`` is deliberately a plain mapping-friendly boundary so callers can
    pass Firestore documents directly.  It accepts camelCase database field
    names and snake_case equivalents for the top-level convenience fields.
    No reads, writes, clocks, randomness, or subprocesses are used here.
    """
    value = _mapping(input)
    snapshot = _mapping(_get(value, "resolutionSnapshot", "resolution_snapshot", "snapshot", default=value))
    rules = _index(_get(value, "rules", default=[]))
    versions = _index(_get(value, "ruleVersions", "rule_versions", default=[]))
    relations = [_mapping(relation) for relation in _get(value, "ruleRelations", "rule_relations", default=[])]
    repository = _mapping(_get(value, "repository", default={}))
    targets = set(_get(repository, "compileTargets", "compile_targets", default=_get(value, "compileTargets", "compile_targets", default=[])))
    rules_path = str(_get(repository, "rulesPath", "rules_path", default=_get(value, "rulesPath", "rules_path", default=".rulebranch/rules"))).strip("/") or ".rulebranch/rules"

    # K7: the snapshot order is already canonical and must never be sorted.
    entries: list[tuple[dict[str, Any], dict[str, Any]]] = []
    for version_id in _get(snapshot, "ruleVersionIds", "rule_version_ids", default=[]):
        version = versions.get(str(version_id))
        if version is None:
            raise ValueError(f"Missing rule version: {version_id}")
        rule_id = str(_get(version, "ruleId", "rule_id", default=""))
        rule = rules.get(rule_id)
        if rule is None:
            raise ValueError(f"Missing rule for version {version_id}: {rule_id}")
        # M13: presentation/personal rules never reach generated artifacts.
        if _get(rule, "enforcement", default=_get(version, "enforcement", default="")) == "personal":
            continue
        entries.append((rule, version))

    # Resolver normally removed override/deny parents already.  Enforce that
    # semantic again here so a caller cannot accidentally compile a stale or
    # hand-assembled snapshot containing a parent.
    initial_ids = {str(_get(rule, "id")) for rule, _ in entries}
    for relation in relations:
        if _get(relation, "relationType", "relation_type", default="") not in {"override", "deny"}:
            continue
        child_id = str(_get(relation, "childRuleId", "child_rule_id", default=""))
        parent_id = str(_get(relation, "parentRuleId", "parent_rule_id", default=""))
        if child_id not in initial_ids:
            continue
        parent, child = rules.get(parent_id), rules.get(child_id)
        if parent is not None and _get(parent, "status", default="active") not in {"active", "stale"}:
            continue
        # Even a scoped/stale/hand-assembled snapshot must not turn an exception
        # into a repository-wide removal. Output instruction paths are global.
        uncovered = uncovered_relation_fields(
            _get(parent or {}, "selector", default=None),
            _get(child or {}, "selector", default=None),
        )
        if uncovered:
            raise ValueError(
                "CONDITIONAL_RELATION_UNSUPPORTED: "
                f"{parent_id} -> {child_id} ({', '.join(uncovered)})"
            )
    excluded_parents = {
        str(_get(relation, "parentRuleId", "parent_rule_id"))
        for relation in relations
        if _get(relation, "relationType", "relation_type", default="") in {"override", "deny"}
        and str(_get(relation, "childRuleId", "child_rule_id", default="")) in initial_ids
    }
    entries = [(rule, version) for rule, version in entries if str(_get(rule, "id")) not in excluded_parents]
    entry_ids = {str(_get(rule, "id")) for rule, _ in entries}
    conflicts = _conflict_ids(_get(snapshot, "conflicts", default=[]))
    override_notes = _override_notes(relations, entry_ids)
    # A tenant can have deny relations for many projects/repositories.  The
    # resolver marks only relations that actually applied to this repository
    # on its execution-only ``resolvedRules`` metadata.  Feeding every tenant
    # relation into _denied.md leaks unrelated policy into this publication.
    denied_child_version_ids = {
        str(_get(_mapping(entry), "ruleVersionId", "rule_version_id", default=""))
        for entry in _get(snapshot, "resolvedRules", "resolved_rules", default=[])
        if _get(_mapping(entry), "resolvedVia", "resolved_via", default="") == "deny"
    }
    denied_child_ids = {
        rule_id for rule_id, rule in rules.items()
        if str(_get(rule, "currentVersionId", "current_version_id", default="")) in denied_child_version_ids
    }
    denied = _denied_entries(relations, rules, versions, denied_child_ids)
    artifacts: list[CompiledArtifact] = []

    aggregate_targets = (
        ("agents-md", "AGENTS.md"),
        ("claude-md", "CLAUDE.md"),
        ("copilot-instructions", ".github/copilot-instructions.md"),
    )
    for target, path in aggregate_targets:
        if target in targets:
            artifacts.append(_artifact(target, path, managed_block(_aggregate_content(entries, conflicts, override_notes)), None))

    if "rulebranch-rules" in targets:
        # Organization and project rules may legally share a key. The Git tree
        # cannot contain two different blobs at the same path, so disambiguate
        # the affected per-rule names (but preserve existing paths otherwise).
        path_counts: dict[tuple[str, str], int] = {}
        for rule, _ in entries:
            identity = (str(_get(rule, "layer", default="")), str(_get(rule, "key", default="")))
            path_counts[identity] = path_counts.get(identity, 0) + 1
        for rule, version in entries:
            layer = str(_get(rule, "layer", default=""))
            key = str(_get(rule, "key", default=""))
            if layer not in {"L1", "L2", "L3"} or not key or "/" in key:
                raise ValueError(f"Invalid per-rule path fields for rule {_get(rule, 'id')}")
            body = _normalise(_approval_header([version]) + "\n\n" + _rule_block(rule, version, conflicts, override_notes, include_heading=True))
            rule_id = str(_get(rule, "id"))
            filename = key if path_counts[(layer, key)] == 1 else f"{key}--{sha256(rule_id.encode('utf-8')).hexdigest()[:12]}"
            artifacts.append(_artifact("rulebranch-rules", f"{rules_path}/{layer}/{filename}.md", body, rule_id))
        # K6: an empty deny list intentionally produces no deletion artifact.
        if denied:
            artifacts.append(_artifact("rulebranch-rules", f"{rules_path}/_denied.md", _denied_content(denied), None))

    # A defensive invariant protects this library if its input shape evolves.
    personal_ids = {str(_get(rule, "id")) for rule in rules.values() if _get(rule, "enforcement", default="") == "personal"}
    assert not any(item.ruleId in personal_ids for item in artifacts)
    if len({item.path for item in artifacts}) != len(artifacts):
        raise ValueError("Rule Compiler produced duplicate artifact paths")
    return artifacts


def _aggregate_content(entries: Sequence[tuple[dict[str, Any], dict[str, Any]]], conflicts: set[str], notes: dict[str, str]) -> str:
    normal = [(rule, version) for rule, version in entries if _get(rule, "enforcement", default=_get(version, "enforcement", default="")) != "advisory"]
    advisory = [(rule, version) for rule, version in entries if _get(rule, "enforcement", default=_get(version, "enforcement", default="")) == "advisory"]
    parts = [_approval_header([version for _, version in entries]), "", "# RuleBranch rules"]
    if normal:
        parts.extend(["", "## Rules"])
        parts.extend(_rule_block(rule, version, conflicts, notes, include_heading=True) for rule, version in normal)
    if advisory:
        parts.extend(["", "## 推奨"])
        parts.extend(_rule_block(rule, version, conflicts, notes, include_heading=True) for rule, version in advisory)
    return _normalise("\n\n".join(parts))


def _rule_block(rule: Mapping[str, Any], version: Mapping[str, Any], conflicts: set[str], notes: Mapping[str, str], *, include_heading: bool) -> str:
    rule_id = str(_get(rule, "id"))
    key = str(_get(rule, "key", default=rule_id))
    enforcement = str(_get(rule, "enforcement", default=_get(version, "enforcement", default="default")))
    parts: list[str] = []
    if rule_id in notes:
        parts.append(f"<!-- Rule {notes[rule_id]} overridden by {rule_id} -->")
    if rule_id in conflicts:
        parts.append(f"<!-- WARNING: Rule {rule_id} conflicts with another active rule; both are emitted. -->")
    if include_heading:
        parts.append(f"## {key}")
    if enforcement == "locked":
        parts.append("**Enforcement: locked**")
    elif enforcement == "advisory":
        parts.append("**Enforcement: advisory (推奨)**")
    # A repository-wide AGENTS.md is read in many directories. Never turn a
    # rule scoped to one language/path/dependency into an unconditional directive.
    selector = _mapping(_get(rule, "selector", default={}))
    constraints = []
    for field, label in (
        ("languages", "言語"), ("frameworks", "フレームワーク"),
        ("directoryGlobs", "ディレクトリ"), ("dependencies", "依存関係")
    ):
        values = _get(selector, field, default=[])
        if isinstance(values, list) and values:
            rendered = ", ".join("`" + " ".join(str(value).split()).replace("`", "\\`") + "`" for value in values)
            constraints.append(f"{label}: {rendered}")
    if constraints:
        parts.append("**適用条件（この条件に該当する場合のみ適用）:** " + " / ".join(constraints))
    content = str(_get(version, "content", default=""))
    if content:
        parts.append(content)
    return "\n\n".join(parts)


def _denied_content(denied: Sequence[tuple[dict[str, Any], dict[str, Any], dict[str, Any]]]) -> str:
    parts = [_approval_header([version for _, _, version in denied]), "", "# Denied rules"]
    for relation, rule, version in denied:
        parts.append("\n\n".join((
            f"## {_get(rule, 'key', default=_get(rule, 'id'))}",
            f"- Rule ID: {_get(rule, 'id')}",
            f"- Denied by: {_get(relation, 'childRuleId', 'child_rule_id', default='unknown')}",
            f"- Rationale: {_get(relation, 'rationale', default='')}",
            str(_get(version, "content", default="")),
        )))
    return _normalise("\n\n".join(parts))


def _artifact(target: str, path: str, body: str, rule_id: str | None) -> CompiledArtifact:
    content = _normalise(body)
    raw = content.encode("utf-8")
    return CompiledArtifact(
        target,
        path,
        sha256(raw).hexdigest(),
        None if len(raw) > MAX_ARTIFACT_CONTENT_BYTES else content,
        len(raw) > MAX_ARTIFACT_CONTENT_BYTES,
        git_blob_sha(content),
        rule_id,
        compilerVersion=COMPILER_VERSION,
        publicationContent=content,
    )


def _normalise(content: str) -> str:
    return content.replace("\r\n", "\n").replace("\r", "\n").lstrip("\ufeff").rstrip("\n") + "\n"


def _override_notes(relations: Sequence[Mapping[str, Any]], entry_ids: set[str]) -> dict[str, str]:
    notes: dict[str, str] = {}
    for relation in relations:
        if _get(relation, "relationType", "relation_type", default="") == "override":
            parent, child = str(_get(relation, "parentRuleId", "parent_rule_id")), str(_get(relation, "childRuleId", "child_rule_id"))
            # Resolver omits the overridden parent from ruleVersionIds.  Keep
            # its required annotation next to the surviving child instead.
            if child in entry_ids: notes[child] = parent
    return notes


def _denied_entries(relations: Sequence[Mapping[str, Any]], rules: Mapping[str, dict[str, Any]], versions: Mapping[str, dict[str, Any]], denied_child_ids: set[str]) -> list[tuple[dict[str, Any], dict[str, Any], dict[str, Any]]]:
    result = []
    for relation in relations:
        if _get(relation, "relationType", "relation_type", default="") != "deny": continue
        child_id = str(_get(relation, "childRuleId", "child_rule_id", default=""))
        if child_id not in denied_child_ids: continue
        rule = rules.get(str(_get(relation, "parentRuleId", "parent_rule_id", default="")))
        if rule is None or _get(rule, "enforcement", default="") == "personal": continue
        version_id = str(_get(rule, "currentVersionId", "current_version_id", default=""))
        version = versions.get(version_id)
        if version is not None: result.append((dict(relation), rule, version))
    return result


def _conflict_ids(conflicts: Sequence[Any]) -> set[str]:
    result: set[str] = set()
    for conflict in conflicts:
        item = _mapping(conflict)
        for name in ("ruleId", "rule_id", "conflictingRuleId", "conflicting_rule_id"):
            if _get(item, name, default=None) is not None: result.add(str(_get(item, name)))
    return result


def _index(items: Sequence[Any] | Mapping[str, Any]) -> dict[str, dict[str, Any]]:
    iterable = items.values() if isinstance(items, Mapping) else items
    return {str(_get(_mapping(item), "id")): _mapping(item) for item in iterable}


def _mapping(value: Any) -> dict[str, Any]:
    if isinstance(value, Mapping): return dict(value)
    if is_dataclass(value): return asdict(value)
    if value is None: return {}
    return dict(vars(value))


def _get(value: Mapping[str, Any], *names: str, default: Any = None) -> Any:
    for name in names:
        if name in value: return value[name]
    return default

