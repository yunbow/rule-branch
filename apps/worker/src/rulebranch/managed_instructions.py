"""Replace only the explicitly owned portion of shared instruction files."""
from __future__ import annotations

BEGIN = "<!-- BEGIN RULEBRANCH MANAGED RULES -->"
END = "<!-- END RULEBRANCH MANAGED RULES -->"
INSTRUCTION_PATHS = {"AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md"}


def managed_block(body: str) -> str:
    if BEGIN in body or END in body:
        raise ValueError("Rule text contains reserved RuleBranch management markers")
    return f"{BEGIN}\n{body.rstrip(chr(10))}\n{END}\n"


def update_instructions(existing: str, generated: str, *, legacy_owned: bool = False) -> str:
    """Preserve every byte outside the block, including newlines and front matter.

    Unmarked, historical generated files are replaced only after their full Git
    blob hash is matched against a previously recorded artifact by the caller.
    Ambiguous ownership stops publication instead of discarding manual edits.
    An empty generated body removes the managed block when a target is disabled.
    """
    begins, ends = existing.count(BEGIN), existing.count(END)
    if begins or ends:
        if begins != 1 or ends != 1:
            raise ValueError("Invalid RuleBranch management markers; repair the file before publication")
        start, end = existing.index(BEGIN), existing.index(END)
        if end < start or (start and existing[start - 1] != "\n"):
            raise ValueError("Invalid RuleBranch management marker order")
        if existing[start + len(BEGIN):start + len(BEGIN) + 1] not in {"\n", "\r"} or (end and existing[end - 1] != "\n"):
            raise ValueError("RuleBranch management marker must occupy its own line")
        after = end + len(END)
        if after < len(existing) and existing[after] not in "\r\n":
            raise ValueError("RuleBranch management marker must occupy its own line")
        # Consume the block's line ending, never the surrounding manual text.
        if existing[after:after + 2] == "\r\n": after += 2
        elif existing[after:after + 1] == "\n": after += 1
        return existing[:start] + generated + existing[after:]
    if existing.startswith("Generated by RuleBranch."):
        if not legacy_owned:
            raise ValueError("Legacy RuleBranch instructions contain unverified edits; add management markers before publication")
        return generated
    if not generated: return existing
    separator = "" if not existing else "\n" if existing.endswith("\n") else "\n\n"
    return existing + separator + generated
