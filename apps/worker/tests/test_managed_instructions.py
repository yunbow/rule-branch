import unittest
from rulebranch.managed_instructions import BEGIN, END, managed_block, update_instructions


class ManagedInstructionsTests(unittest.TestCase):
    def test_initial_append_and_replacement_preserve_manual_bytes(self):
        manual = "---\r\napplyTo: '**'\r\n---\r\n# Team conventions\r\nUse pnpm.\r\n"
        first = update_instructions(manual, managed_block("Old generated rule\n"))
        suffix = "\n# Local notes\r\nDo not change these.\r\n"
        second = update_instructions(first + suffix, managed_block("New generated rule\n"))
        self.assertTrue(second.startswith(manual))
        self.assertTrue(second.endswith(suffix))
        self.assertNotIn("Old generated rule", second)
        self.assertEqual(second.count(BEGIN), 1)
        self.assertEqual(update_instructions(second, managed_block("New generated rule\n")), second)

    def test_removing_target_preserves_manual_text(self):
        self.assertEqual(update_instructions("prefix\n" + managed_block("rules") + "suffix", ""), "prefix\nsuffix")

    def test_legacy_ownership_must_be_verified(self):
        legacy = "Generated by RuleBranch. Do not edit manually.\n\nOld rules\n"
        with self.assertRaisesRegex(ValueError, "unverified edits"):
            update_instructions(legacy + "Manual note", managed_block("new"))
        self.assertEqual(update_instructions(legacy, managed_block("new"), legacy_owned=True), managed_block("new"))

    def test_ambiguous_markers_stop_publication(self):
        for value in [BEGIN, END, END + "\n" + BEGIN, managed_block("one") + managed_block("two"), "inline " + managed_block("rules")]:
            with self.subTest(value=value), self.assertRaises(ValueError):
                update_instructions(value, managed_block("new"))
        with self.assertRaises(ValueError): managed_block("untrusted " + END)
