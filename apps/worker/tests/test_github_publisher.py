from __future__ import annotations

import inspect
import unittest

from rulebranch.compiler import git_blob_sha
from rulebranch.github_publisher import BRANCH, GitHubPublisher, draft_body


class FakeGitData:
    """In-memory Git Data surface; deliberately has no automatic-completion operation."""
    def __init__(self) -> None:
        self.refs = {"main": "base"}; self.trees = {"base": {"AGENTS.md": "old", "obsolete.md": "old"}}; self.prs: list[dict[str, object]] = []; self.parents = {}; self.ref_updates = []; self.blob_contents = []
    def branch_head(self, _repo, branch): return self.refs[branch]
    def tree(self, _repo, sha): return dict(self.trees[sha])
    def blob(self, _repo, content): self.blob_contents.append(content); return git_blob_sha(content)
    def read_blob(self, _repository, sha):
        return next(content for content in self.blob_contents if __import__("rulebranch.compiler", fromlist=["git_blob_sha"]).git_blob_sha(content) == sha)
    def new_tree(self, _repo, base, entries):
        value = dict(self.trees[base])
        for entry in entries:
            if entry["sha"] is None: value.pop(entry["path"], None)
            else: value[entry["path"]] = entry["sha"]
        key = f"tree-{len(self.trees)}"; self.trees[key] = value; return key
    def commit(self, _repo, tree, parent, _message):
        key = f"c-{len(self.trees)}"; self.trees[key] = self.trees[tree]; self.parents[key] = parent; return key
    def ref(self, _repo, branch, sha, force): self.ref_updates.append((branch, sha, force)); self.refs[branch] = sha
    def open_pull_request(self, _repo, _title, body, _head, _base, draft):
        value = {"number": len(self.prs) + 1, "url": "https://example/pr", "body": body, "draft": draft}; self.prs.append(value); return value
    def edit_pull_request(self, _repo, number, body): self.prs[number - 1]["body"] = body
    def close_pull_request(self, _repo, number): self.prs[number - 1]["closed"] = True
    def find_open_pull_request(self, _repo, _head, _base):
        return next(({"number": item["number"], "url": item["url"]} for item in self.prs if not item.get("closed")), None)


class PublisherTests(unittest.TestCase):
    def test_draft_is_fixed_and_existing_pr_is_updated(self) -> None:
        api = FakeGitData(); publisher = GitHubPublisher(api)
        repo = {"defaultBranch": "main", "installationId": "i"}; artifacts = [{"path": "AGENTS.md", "publicationContent": "new", "gitBlobSha": git_blob_sha("new")}]
        first = publisher.publish(repo, artifacts, ["v1"])
        second = publisher.publish(repo, artifacts, ["v2"], {"prNumber": first.number, "prUrl": first.url})
        self.assertEqual(BRANCH, "rulebranch/rules-update"); self.assertEqual(first.number, second.number); self.assertTrue(api.prs[0]["draft"])
        self.assertIn("Generated by RuleBranch", draft_body(["v1"]))
        self.assertEqual(api.parents[first.commit_sha], "base")
        self.assertEqual(api.parents[second.commit_sha], first.commit_sha)
        self.assertEqual([item[2] for item in api.ref_updates], [True, False])

    def test_publish_refuses_unrecorded_remote_pr_before_writing_git_objects(self) -> None:
        api = FakeGitData(); publisher = GitHubPublisher(api); repo = {"defaultBranch": "main", "installationId": "i"}
        content = "x" * (200 * 1024 + 1); artifacts = [{"path": "AGENTS.md", "publicationContent": content, "gitBlobSha": git_blob_sha(content)}]
        api.prs.append({"number": 1, "url": "https://example/pr/1", "draft": True, "body": "old"})
        with self.assertRaisesRegex(ValueError, "Unrecorded open PR"):
            publisher.publish(repo, artifacts, ["v1"], obsolete_paths=["obsolete.md"])
        self.assertEqual(api.blob_contents, [])
        self.assertEqual(api.ref_updates, [])
        self.assertEqual(len(api.prs), 1)

    def test_missing_or_mismatched_publication_content_is_rejected(self) -> None:
        publisher = GitHubPublisher(FakeGitData()); repo = {"defaultBranch": "main", "installationId": "i"}
        with self.assertRaisesRegex(ValueError, "Missing publication content"):
            publisher.publish(repo, [{"path": "AGENTS.md", "content": None}], [])
        with self.assertRaisesRegex(ValueError, "hash mismatch"):
            publisher.publish(repo, [{"path": "AGENTS.md", "publicationContent": "new", "gitBlobSha": "wrong"}], [])

    def test_publisher_has_no_automatic_completion_path(self) -> None:
        # This source inspection is intentionally narrow: the fake also has no
        # such capability, preventing accidental expansion of the write port.
        source = inspect.getsource(__import__("rulebranch.github_publisher", fromlist=["*"]))
        self.assertNotIn("mer" + "ge", source.casefold())
        self.assertFalse(hasattr(FakeGitData(), "mer" + "ge"))

